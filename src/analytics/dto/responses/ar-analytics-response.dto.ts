import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class CreditOverviewDto {
  @ApiProperty({
    description: 'Total combined credit limit extended to wholesale customers',
    example: 500000.0,
  })
  total_credit_extended!: number;

  @ApiProperty({
    description: 'Total active outstanding balance owed by wholesale customers',
    example: 125000.5,
  })
  total_outstanding_debt!: number;

  @ApiProperty({
    description: 'Percentage of total extended credit currently in use',
    example: 25.0,
  })
  credit_utilization_percentage!: number;

  @ApiProperty({
    description: 'Total number of active wholesale customer accounts',
    example: 24,
  })
  total_wholesale_accounts!: number;
}

export class ArAgingItemDto {
  @ApiProperty({ description: 'Wholesale customer ID', example: 5 })
  customerId!: number;

  @ApiProperty({ description: 'Company name', example: 'Acme Hardware Corp' })
  company_name!: string;

  @ApiProperty({ description: 'Contact person name', example: 'John Doe' })
  customer_name!: string;

  @ApiProperty({
    description: 'Contact phone number',
    example: '+639171234567',
  })
  contact_number!: string;

  @ApiProperty({
    description: 'Total outstanding debt balance for this customer',
    example: 45000.0,
  })
  total_outstanding_balance!: number;

  @ApiProperty({
    description: 'Current debt amount (not yet overdue)',
    example: 20000.0,
  })
  current_amount!: number;

  @ApiProperty({
    description: 'Debt amount 1–30 days overdue',
    example: 15000.0,
  })
  days_1_30_overdue!: number;

  @ApiProperty({
    description: 'Debt amount 31–60 days overdue',
    example: 10000.0,
  })
  days_31_60_overdue!: number;

  @ApiProperty({ description: 'Debt amount 60+ days overdue', example: 0.0 })
  days_60_plus_overdue!: number;
}

export class TopCreditCustomerDto {
  @ApiProperty({ description: 'Wholesale customer ID', example: 5 })
  customerId!: number;

  @ApiProperty({ description: 'Company name', example: 'Acme Hardware Corp' })
  company_name!: string;

  @ApiProperty({
    description: 'Total sales volume generated by this customer',
    example: 185000.0,
  })
  total_sales_volume!: number;

  @ApiProperty({
    description: 'Total debt payments successfully settled by customer',
    example: 140000.0,
  })
  total_settled_payments!: number;

  @ApiProperty({ description: 'Current outstanding balance', example: 45000.0 })
  current_outstanding_balance!: number;

  @ApiProperty({
    description: 'Credit settlement promptness score (0–100%)',
    example: 85.5,
  })
  promptness_score!: number;
}

export class AccountsReceivableResponseDto {
  @ApiProperty({
    type: CreditOverviewDto,
    description: 'Overall credit portfolio metrics',
  })
  credit_overview!: CreditOverviewDto;

  @ApiProperty({
    type: [ArAgingItemDto],
    description: 'List of wholesale accounts categorized by debt age',
  })
  aging_table!: ArAgingItemDto[];

  @ApiProperty({
    type: [TopCreditCustomerDto],
    description: 'Ranking of wholesale clients by sales volume and promptness',
  })
  top_credit_customers!: TopCreditCustomerDto[];
}
